
#*元组
#派森将不能修改的值称为不可变的，而不可变的列表称为元组（tuple）



#?定义元组
#使用圆括号（）来定义元组
tuple=(114,514,1919,810)
#如果此时对元组进行修改，则会报错
#元组的“不可修改”，指的是一种极其严格的操作：改变元组内部的元素，或者改变元组的长度。
print(tuple[::-1])  #这个是可执行的，因为切片操作相当于先复制，然后创造了个“新元组”



#?遍历元组中的所有值
tuple=(114,514,1919,810)
for n in tuple:
    print(n)



#?修改元组变量
#虽然不能修改元组的元素，但可以给表示元组的变量赋值。比如，要修改旧元组数据，可重新定义整个元组，再搞个新元组，再输出
#有点“结果导向型”的感觉
n=(27,78)
print(f'old神秘数字：')
for s in n:
    print(s)
n=(1000,7)
print(f'\nnew神秘数字：')
for s in n:
    print(s)