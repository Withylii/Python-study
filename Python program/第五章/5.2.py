#?random（）学习
#终极避坑与对比总结（贴在你的笔记里）：
#函数	                            作用	                            返回值	                        是否修改原列表
#random.choice(列表)	            随机取1个	                        ✅ 有（单个元素）	           ❌ 否
#random.choices(列表, k=n)	        随机取n个（可重复）	                 ✅ 有（新列表）	                ❌ 否
#random.sample(列表, k=n)	        随机取n个（不重复）	                 ✅ 有（新列表）	                ❌ 否
#random.shuffle(列表)	            原地打乱顺序	                    ❌ 无（返回 None）	            ✅ 是

#1. random.choice(列表) —— 随机抽取“一个”元素
#作用：从列表里随机挑一个元素给你。
#返回值：有返回值！你需用变量接住它，或者直接打印。
#机器人实战：随机选择一个巡逻点。

#2. random.choices(列表, k=数量) —— 随机抽取“多个”（有放回）
#作用：随机抽出多个元素，组成一个新列表。
#注意：k 是你想抽取的数量。因为是“有放回”抽取，抽出来的元素可能会重复。
#返回值：有返回值，返回一个新列表。

#3. random.sample(列表, k=数量) —— 随机抽取“多个”（无放回）
#作用：随机抽出多个元素，绝不重复（无放回抽样）。
#返回值：有返回值，返回一个新列表。
#机器人实战：机器人的任务调度，每天随机选 3 个不重复的传感器进行校准。

#4. random.shuffle(列表) —— 原地打乱列表顺序
#作用：把列表里的元素顺序彻底打乱（洗牌）。
#⚠️ 极度重要（复习你踩过的坑）：这是原地修改（In-place Modification）！它没有返回值（返回 None）。
#机器人实战：打乱机器人的任务顺序，避免它每次都按照同样的固定路线走。







