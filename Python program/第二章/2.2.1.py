#所以说，变量的意思是你只要写个任意字母，加个等号，左边就是变量，右边就是你打的东西的“值”，然后再输出时，就不需要再打上下引号了
#！变量名只能包含：字母、数字、下划线。变量名能以字母或下划线打头。你能用任何字母和下划线打头，但就是不能以数字打头，之后内容你随便字母数字下划线排列组合。可：lover_1 or _1lover不可：1_lover
