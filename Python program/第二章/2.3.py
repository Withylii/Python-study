#? f字符串的使用方法
#!f-string 的公式是：f + 引号 + 大括号{}
speed = 1.5
# 必须用 + 拼接，而且数字必须强转成字符串（str），不然报错
message = "机器人的速度是 " + str(speed) + " 米/秒"
print(message)#非f字符串

speed = 1.5
# 在引号前面加个 f，然后用大括号 {} 把变量框起来，直接塞进去
message = f"机器人的速度是 {speed} 米/秒"
print(message)#用f字符串

#!在字符串的引号前面，必须加个小写的 f（比如 f"..." 或 f'...'）。
#!在字符串内部，用英文大括号 {} 包住你想塞进去的变量或表达式。
#!如果 {} 里是变量，变量必须先定义，不然会报错。
#!f必须写在引号外面：f"你好" ✅，"f你好" ❌（这样会变成普通字符串）。
#!大括号必须是英文半角的 {}，不能用中文的 ｛｝。
#!大括号里不能直接放反斜杠 \（比如 f"{\n}" 会报错），需要用到变量中转。
r = 0.5
# 老写法：要算好周长，再转字符串
circumference = 2 * 3.14 * r
print("周长是 " + str(circumference))

# f-string：直接在里面算，算完自动转字符串
print(f"周长是 {2 * 3.14 * r}") 
#!f字符串既可以在大括号内直接输入变量，得出对应值，也可以实现在大括号内进行法则运算，并且结果直接是字符串，还不需要加加号。相当于你写了啥，出来就是啥，只需要直接拼接，而不需要加号等乱七八糟的只为构成一句话
#!f字符串，你直接写文本，要计算的活的东西，用大括号{}连着文本直接内部计算，不需要加号连接！！直接打变量名，不需要打对应的值与转换方法，不需要加号！！
#!f字符串最大优势：不用打+！！！并且可以直接输变量名！！！且多个文本不用各自打引号！！！
#!f字符串引号内，大括号外，普通文本，遵循单双复用，反斜杠法则。但是大括号{}内，只能单双复用，反斜杠绝对不能用！！！！最好用变量中转！
#!f字符串还可以用来表示变量的值
#!f字符串也是字符串，是最终输出的东西
#!变量才是操作对象，值只是设定的
#!至于你用字符串还是f字符串，对于值的定义无所谓，但是
first_name=f"Hoshii"
last_name=f'Miki'
full_name=f'{first_name} {last_name}'#此步就已经表示变量的值通过字符串操作完了，结果会是纯文本
message=f'Hello,{full_name}!'#同理，下步print就不需要再加字符串了，因为变量的值已经是纯文本了。否则print加字符串就只会是另一个文本，无变量含义
print(f"full_name")
print(full_name)
print(message)
print(f'nice to meet you,{full_name}!')
#!print(f'full_name')≠print(full_name)，前者通过f字符串，只输入文本本身。后者才是真正输出你先定定义了的full_name的值！
#!如果print（）内有文本类型内容，则需要用字符串，也可以先用变量表示成文本，再直接输入变量。但f字符串可以文本变量直接拼接
p=f'gold'
print(f'{p.upper()}')
