
#*2.3 字符串
#字符串（string）就是一系列字符，就是文本的意思！就是指你输出的会是文本，而不是程序！在派桑中，用引号引起的都是字符串，其中引号可以是单引号，也可以是双引号。
#!字符指的就是一系列乱七八糟的字母汉字数字符号，然后加个引号串起来，引号一串就叫做“字符串”，还挺生动形象，“字符串”本身也是个字符串
#!引号必须用英文输入！！！必须都是英文半角输入法！！！
#!最外边的引号是字符串的字母，不会输出，不是语句的意思！！要输出语句自己再加！！
"this is a string."
'this is also a string.'
#单引号双引号随便互相包含，但是绝对不能单包单，双包双！！
x="'You\'re so cute.'"
print(x)
#包含同种引号的方法：
#!1，使用反斜杠\转义，即在同一引号前加反斜杠代表了这是“内部”的引号，转义了。在里面的单引号前面加一个反斜杠 \，告诉 Python：“这个单引号是字符串的内容，不是结束标志。”
s = "He said \"Hello\" to me."
print(s) # 输出：He said "Hello" to me

v='I\'m a hardworking student.'
print(v)

m="\"I \'love\' you.\""
print(m)
#2，使用“三引号”法，三引号 ''' 或 """ 强大得多，里面可以随意包含单引号或双引号，还能换行。
#!三引号法，最两边的三引号不能够再接同一个引号！如果要引号表示和三引号连着的内容，必须用和三引号不同的引号！！！
#!三引号太ex了，还是老老实实单双复用和反斜杠吧！！
s = '''He said: "I'm a robot."'''
print(s)  # 输出：He said: "I'm a robot"

k="""there is a famous saying,'the only "fear" is the fear 'itself.''"""
print(k)

#修改字符串大小写的方法
#!"方法"在python里是什么东西？方法（method）是python可以对数据（变量、值）执行的各类操作，包括.title()、.upper()、.lower()、.strip()，这些都是方法
#!有的method括号内不加东西功能就行，比如.title()，只是为了保持统一。但比如.count()的括号内必须得加东西，因为这方法代表了你要数什么东西的数量，括号内就是你要找的东西的名字
#!方法的(.)的前面，需要写你方法所操作执行的对象（即变量、值、whatever）
#.title()：每个单词首字母大写
#.upper()：全大写
#.lower()：全小写（机器人指令常用来做大小写兼容，比如接收的指令是 "FORWARD"，你转成小写 "forward" 再判断）
#.strip()：去除首尾空格（处理传感器或串口读来的数据必用，去掉换行符）
#.replace(旧, 新)：替换内容
#.find(子串)：找位置，找不到返回 -1
#.count(子串)：统计出现次数
#.isdigit()：是不是全数字（判断用户输入是否合法）
#.startswith(前缀)：以...开头（判断文件路径是不是某个目录）
#.split(分隔符)：把字符串切分成列表（把 "1,2,3" 切成 ["1", "2", "3"]，处理CSV数据必用）
#.join(列表)：把列表拼成字符串
#.center(宽度, 填充符)：居中
#.ljust() / .rjust()：左对齐 / 右对齐
#.append(元素)：在末尾追加
#.insert(索引, 元素)：在指定位置插入
#.pop()：删除并返回最后一个元素（机器人任务栈、历史路径记录常用）
#.remove(元素)：删除指定的第一个匹配项
#.sort()：永久排序
#.reverse()：反转列表
#.count(元素)：统计元素出现次数
#.index(元素)：找元素的下标
#.get(键, 默认值)：极其重要！ 找不到键时返回默认值，而不是直接报错。（解析机器人的 JSON 参数时必用）
#.keys()：获取所有键
#.values()：获取所有值
#.items()：获取键值对，常配合 for 循环遍历
#.update(另一个字典)：合并字典
#type(数据)：查看数据类型（比如 <class 'str'>）
#len(数据)：看长度（比如字符串有几个字，列表有几个元素）
#dir(数据)：魔法工具。不记得某个数据类型有什么方法时，用它列出来！
#help(数据.方法)：查看官方说明（比如 help("abc".title) 会告诉你 title 怎么用）
#help("abc".title)

