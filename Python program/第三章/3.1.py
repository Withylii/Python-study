#?访问列表元素/索引从0而不是1开始
#列表是有序集合，要访问元素，只需要将元素的位置（索引）告诉python
#访问元素，可以指出列表名称，再在后面打上方括号，方括号内指出元素的索引即可
#!索引即为元素的顺序，在python中，从左往右第一位元素的索引为0。负数则表示为从右往左的位置，倒数，比如[-1]就是指列表中最后一个元素。索引可以是数字，也可以是数字赋值了的变量
#!索引数决不能越界，否则将会报错
k=['00001','sun','moon']
print(int(k[0]),k[2].title())        #索引选中的列表中的元素，当然可以进行方法操作
m=[12,0.3,0.08]
print(m[1]*m[2],'\nt.title()')       #依旧引号内的是纯文本，注意了



