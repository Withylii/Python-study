
#*3.1列表
#列表list是由一系列按特定顺序排列的元素组成的。你可以将任何东西加入列表中，且列表中通常包含多个元素，因此可以给列表指定一个表示复数的名称，比如letters
#在派森中，用方括号[]表示列表，用逗号分隔其中的元素
#列表中的元素可以是字符串，可以是数字，可以是任何东西
#可以将列表赋值给变量
l=['haruga','chihaya','miki']
